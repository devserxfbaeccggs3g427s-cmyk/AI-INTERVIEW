"use client";

import Link from "next/link";
import { useState } from "react";

import { Icon } from "@/components/ui/icon";
import { cn } from "@/lib/cn";

/**
 * Báo cáo kết quả phỏng vấn (S18 — FR-MI-09).
 *
 * ⚠️ FR-MI-09 — **3 điểm mạnh** có trích dẫn nguyên văn đã kiểm chứng +
 * **3 điểm yếu** + đề xuất luyện tiếp trỏ về cây kỹ năng.
 *
 * ⚠️ P3 — đề xuất luyện tiếp gắn với `skillId` đã có bằng chứng ⇒ bấm là
 * luyện đúng chỗ yếu, không phải gợi ý chung chung.
 */

export interface ReportStrength {
  title: string;
  quote: string | null;
  turnIndex: number;
  comment: string;
  autoGenerated: boolean;
}

export interface ReportWeakness {
  title: string;
  turnIndex: number;
  comment: string;
  suggestion: string;
  autoGenerated: boolean;
}

export interface ReportNextPractice {
  skillId: string;
  skillName: string;
  evidenceCount: number;
  action: string;
}

export interface InterviewReportDTO {
  overallNote: string;
  strengths: ReportStrength[];
  weaknesses: ReportWeakness[];
  nextPractices: ReportNextPractice[];
  rubric: Record<string, number>;
  totalScore: number;
}

export interface InterviewReportProps {
  sessionId: string;
  report: InterviewReportDTO | null;
  totalScore: number | null;
  profileLabel: string;
  jobTitle: string;
  aiEnabled: boolean;
}

const CRITERION_LABELS: Record<string, string> = {
  accuracy: "Độ chính xác",
  depth: "Chiều sâu",
  reasoning: "Lập luận",
  communication: "Truyền đạt",
  tradeoff: "Đánh đổi",
};

export function InterviewReport({
  sessionId,
  report,
  totalScore,
  profileLabel,
  jobTitle,
  aiEnabled,
}: InterviewReportProps) {
  const [generating, setGenerating] = useState(false);
  const [error, setError] = useState<string | null>(null);

  async function generate() {
    setGenerating(true);
    setError(null);

    try {
      const res = await fetch("/api/interview/report", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ sessionId }),
      });

      const payload = await res.json();
      if (!payload.ok) {
        setError(payload.message ?? "Không tạo được báo cáo");
        return;
      }

      routerRefresh();
    } catch {
      setError("Không kết nối được");
    } finally {
      setGenerating(false);
    }
  }

  function routerRefresh() {
    // Báo cáo lưu trong DB ⇒ cần refresh server component.
    window.location.reload();
  }

  return (
    <div className="space-y-gutter-md">
      <header className="space-y-space-sm">
        <h1 className="font-headline-lg text-headline-lg text-on-surface">
          Kết quả phỏng vấn
        </h1>
        <p className="text-body-md text-body-md text-on-surface-variant">
          {profileLabel} · {jobTitle}
        </p>
      </header>

      {/* Chưa có báo cáo */}
      {!report && (
        <section className="rounded-xl bg-surface-container p-space-lg">
          <h2 className="font-headline-md text-headline-md text-on-surface">
            Chưa có báo cáo
          </h2>
          <p className="mt-space-sm text-body-md text-body-md text-on-surface-variant">
            Báo cáo tổng hợp 3 điểm mạnh, 3 điểm yếu và đề xuất luyện tiếp
            được sinh khi phiên kết thúc.
          </p>

          {totalScore !== null && (
            <p className="mt-space-md font-headline-lg text-headline-lg text-primary tabular">
              {totalScore.toFixed(1)}
              <span className="font-label-sm text-label-sm text-outline"> / 5</span>
            </p>
          )}

          <button
            type="button"
            onClick={() => void generate()}
            disabled={generating || !aiEnabled}
            className="mt-space-md inline-flex items-center gap-1 rounded-lg bg-primary-container px-4 py-2 font-label-md text-label-md font-semibold text-on-primary transition hover:brightness-105 disabled:opacity-50 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-primary"
          >
            <Icon name="bolt" size={16} />
            {generating ? "Đang tạo…" : "Tạo báo cáo"}
          </button>

          {!aiEnabled && (
            <p className="mt-space-sm inline-flex items-center gap-1 font-label-sm text-label-sm text-outline">
              <Icon name="lock" size={12} />
              Chưa có API key — tạo báo cáo cần API key
            </p>
          )}

          {error && (
            <p role="alert" className="mt-space-sm font-label-sm text-label-sm text-error">
              {error}
            </p>
          )}
        </section>
      )}

      {/* Có báo cáo */}
      {report && (
        <>
          {/* Tổng điểm + rubric */}
          <section className="rounded-xl bg-surface-container p-space-lg">
            <div className="flex flex-wrap items-baseline justify-between gap-space-sm">
              <h2 className="font-headline-md text-headline-md text-on-surface">
                5 Tiêu chí Rubric
              </h2>
              <span className="font-headline-lg text-headline-lg text-primary tabular">
                {report.totalScore.toFixed(1)}
                <span className="font-label-sm text-label-sm text-outline"> / 5</span>
              </span>
            </div>

            <ul className="mt-space-md space-y-space-xs">
              {Object.entries(report.rubric).map(([key, value]) => (
                <li key={key} className="flex items-center gap-space-sm">
                  <span className="w-28 shrink-0 font-body-sm text-body-sm text-on-surface-variant">
                    {CRITERION_LABELS[key] ?? key}
                  </span>
                  <span
                    className="h-1.5 flex-1 overflow-hidden rounded-full bg-surface-container-highest"
                    aria-hidden="true"
                  >
                    <span
                      className="block h-full rounded-full bg-primary"
                      style={{ width: `${(Number(value) / 5) * 100}%` }}
                    />
                  </span>
                  <span className="w-8 shrink-0 text-right font-code-md text-code-md text-on-surface tabular">
                    {Number(value).toFixed(1)}
                  </span>
                </li>
              ))}
            </ul>

            <p className="mt-space-md text-body-md text-body-md text-on-surface">
              {report.overallNote}
            </p>
          </section>

          {/* 3 điểm mạnh */}
          <section className="rounded-xl bg-surface-container-low p-space-lg">
            <h2 className="font-headline-md text-headline-md text-on-surface">
              3 Điểm mạnh cụ thể
            </h2>

            <ul className="mt-space-md space-y-space-md">
              {report.strengths.map((item, index) => (
                <li key={index}>
                  <p className="font-body-md text-body-md text-on-surface">
                    {item.title}
                  </p>
                  {item.quote && (
                    <blockquote className="mt-space-xs border-l-2 border-primary pl-space-sm text-body-sm text-body-sm text-on-surface-variant">
                      {item.quote}
                    </blockquote>
                  )}
                  <p className="mt-space-xs font-label-sm text-label-sm text-outline">
                    Lượt {item.turnIndex} · {item.comment}
                  </p>
                </li>
              ))}
            </ul>
          </section>

          {/* 3 điểm yếu */}
          <section className="rounded-xl bg-surface-container-low p-space-lg">
            <h2 className="font-headline-md text-headline-md text-on-surface">
              3 Điểm yếu cần khắc phục
            </h2>

            <ul className="mt-space-md space-y-space-md">
              {report.weaknesses.map((item, index) => (
                <li key={index}>
                  <p className="font-body-md text-body-md text-on-surface">
                    {item.title}
                  </p>
                  <p className="mt-space-xs font-label-sm text-label-sm text-outline">
                    Lượt {item.turnIndex} · {item.comment}
                  </p>
                  <p className="mt-space-xs text-body-sm text-body-sm text-on-surface-variant">
                    → {item.suggestion}
                  </p>
                </li>
              ))}
            </ul>
          </section>

          {/* Đề xuất luyện tiếp */}
          {report.nextPractices.length > 0 && (
            <section className="rounded-xl bg-surface-container-low p-space-lg">
              <h2 className="font-headline-md text-headline-md text-on-surface">
                Đề xuất luyện tiếp
              </h2>

              <ul className="mt-space-md space-y-space-sm">
                {report.nextPractices.map((item) => (
                  <li
                    key={item.skillId}
                    className="flex flex-wrap items-start justify-between gap-space-sm"
                  >
                    <span className="min-w-0">
                      <span className="block font-body-md text-body-md text-on-surface">
                        {item.action}
                      </span>
                      <span className="block font-label-sm text-label-sm text-outline">
                        {item.skillName} · {item.evidenceCount} bằng chứng
                      </span>
                    </span>
                    <Link
                      href={`/skills/${item.skillId}`}
                      className="shrink-0 rounded-lg bg-surface-container-high px-3 py-1.5 font-label-sm text-label-sm text-on-surface transition hover:bg-surface-container-highest focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-primary"
                    >
                      Xem kỹ năng
                    </Link>
                  </li>
                ))}
              </ul>
            </section>
          )}

          {/* Hành động */}
          <div className="flex flex-wrap gap-space-sm">
            <Link
              href={`/interview/setup`}
              className={cn(
                "inline-flex items-center gap-1 rounded-lg bg-primary-container px-4 py-2 font-label-md text-label-md font-semibold text-on-primary transition hover:brightness-105 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-primary",
              )}
            >
              <Icon name="refresh" size={16} />
              Làm lại với hồ sơ này
            </Link>

            <Link
              href={`/api/interview/sessions/${sessionId}`}
              className="inline-flex items-center gap-1 rounded-lg bg-surface-container-high px-4 py-2 font-label-md text-label-md text-on-surface transition hover:bg-surface-container-highest focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-primary"
            >
              <Icon name="download" size={16} />
              Xuất báo cáo JSON
            </Link>
          </div>
        </>
      )}
    </div>
  );
}
