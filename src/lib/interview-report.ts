/**
 * Chuẩn hoá báo cáo AI-13 + verify trích dẫn (FR-MI-08, AC-MI-16).
 *
 * ⚠️ R-MI-4 — AI bịa trích dẫn là mất niềm tin vào cả báo cáo ⇒ **verify**
 * `answer.includes(quote)` trước khi lưu; không khớp thì bỏ trích dẫn, chỉ
 * giữ nhận xét.
 *
 * Nguồn: `.kiro/specs/mock-interview/design.md` §3.6.
 */

import { computeSessionRubric } from "@/lib/interview-rubric";
import type { QuestionKind } from "@/lib/interview";
import type { Report } from "@/lib/interview-prompts";

/** 1 lượt trong transcript (đã trả lời). */
export interface TurnTranscript {
  /** 1-based. */
  readonly index: number;
  readonly question: string;
  readonly kind: QuestionKind;
  readonly answer: string | null;
  readonly skillName: string | null;
  readonly total: number | null;
  /** key → điểm của lượt đó. */
  readonly rubric: Record<string, number>;
}

export interface NormalizedStrength {
  readonly title: string;
  /** `null` khi trích dẫn không khớp nguyên văn. */
  readonly quote: string | null;
  readonly turnIndex: number;
  readonly comment: string;
  /** `true` khi hệ thống tự sinh (AI không đủ 3 mục). */
  readonly autoGenerated: boolean;
}

export interface NormalizedWeakness {
  readonly title: string;
  readonly turnIndex: number;
  readonly comment: string;
  readonly suggestion: string;
  readonly autoGenerated: boolean;
}

export interface NextPractice {
  readonly skillId: string;
  readonly skillName: string;
  readonly evidenceCount: number;
  readonly action: string;
}

export interface NormalizedReport {
  readonly overallNote: string;
  readonly strengths: NormalizedStrength[];
  readonly weaknesses: NormalizedWeakness[];
  readonly nextPractices: NextPractice[];
  readonly rubric: Record<string, number>;
  readonly totalScore: number;
}

/** Số mục điểm mạnh / điểm yếu **luôn** đúng (AC-9). */
export const REPORT_ITEM_COUNT = 3;

/**
 * `true` nếu `quote` là nguyên văn (sau khi chuẩn hoá whitespace) trong `answer`.
 *
 * `answer === null` ⇒ `false` (câu chưa trả lời không thể có trích dẫn).
 */
export function isVerbatimQuote(quote: string, answer: string | null): boolean {
  if (answer === null) return false;

  const normalizedQuote = quote.replace(/\s+/g, " ").trim();
  if (normalizedQuote.length === 0) return false;

  const normalizedAnswer = answer.replace(/\s+/g, " ").trim();
  return normalizedAnswer.includes(normalizedQuote);
}

/**
 * Sinh đề xuất luyện tiếp khi AI trả `nextPractices` rỗng hoặc `skillId` không hợp lệ.
 *
 * Dùng node yếu nhất trong `focused` (cùng thứ tự 4 khoá của `weak-skills.ts`).
 */
export function buildFallbackPractices(
  focused: ReadonlyArray<{
    skillId: string;
    skillName: string;
    evidenceCount: number;
  }>,
): NextPractice[] {
  if (focused.length === 0) return [];

  const weakest = [...focused].sort((a, b) => {
    if (a.evidenceCount !== b.evidenceCount) return a.evidenceCount - b.evidenceCount;
    return a.skillName.localeCompare(b.skillName);
  })[0];

  return [
    {
      skillId: weakest.skillId,
      skillName: weakest.skillName,
      evidenceCount: weakest.evidenceCount,
      action: `Tạo 3 bài tập về ${weakest.skillName}`,
    },
  ];
}

/** Tìm lượt có điểm thấp nhất — dùng khi AI trả `turnIndex` không hợp lệ. */
function lowestScoredTurnIndex(transcript: readonly TurnTranscript[]): number {
  let best: TurnTranscript | null = null;

  for (const turn of transcript) {
    if (turn.answer === null) continue;
    if (best === null) {
      best = turn;
      continue;
    }
    const current = turn.total ?? 5;
    const incumbent = best.total ?? 5;
    if (current < incumbent) best = turn;
  }

  return best?.index ?? transcript[0]?.index ?? 1;
}

/** `turnIndex` hợp lệ = nằm trong `[1, số câu đã trả lời]`. */
function isValidTurnIndex(turnIndex: number, answeredCount: number): boolean {
  return Number.isInteger(turnIndex) && turnIndex >= 1 && turnIndex <= answeredCount;
}

/**
 * Chuẩn hoá report AI-13 về đúng shape của spec.
 *
 * Thứ tự áp dụng (design.md §3.6):
 * 1. Cắt/điền **đúng 3** mạnh + 3 yếu.
 * 2. Verify trích dẫn — không khớp ⇒ `quote = null` (giữ `comment`).
 * 3. Validate `turnIndex` — không hợp lệ ⇒ gán câu có điểm thấp nhất.
 * 4. Validate `nextPractices` — `skillId` không thuộc `skillsFocused` ⇒ fallback.
 * 5. Tính `rubric` lại từ transcript (không tin AI).
 */
export function normalizeReport(
  raw: Report,
  transcript: readonly TurnTranscript[],
  focused?: ReadonlyArray<{
    skillId: string;
    skillName: string;
    evidenceCount: number;
  }>,
): NormalizedReport {
  const answered = transcript.filter((turn) => turn.answer !== null);
  const answeredCount = answered.length;
  const fallbackIndex = lowestScoredTurnIndex(transcript);

  /* ── 1 + 2 + 3 — điểm mạnh ─────────────────────────────────────────────── */
  const strengths: NormalizedStrength[] = [];

  for (const item of raw.strengths.slice(0, REPORT_ITEM_COUNT)) {
    const turnIndex = isValidTurnIndex(item.turnIndex, answeredCount)
      ? item.turnIndex
      : fallbackIndex;

    const turn = transcript.find((t) => t.index === turnIndex);
    const quote = isVerbatimQuote(item.quote, turn?.answer ?? null) ? item.quote : null;

    strengths.push({
      title: item.title,
      quote,
      turnIndex,
      comment: item.comment,
      autoGenerated: false,
    });
  }

  // Điền cho tới đủ 3 bằng mục suy ra từ rubric thấp nhất (gắn autoGenerated).
  while (strengths.length < REPORT_ITEM_COUNT) {
    strengths.push(autoStrength(strengths.length, transcript, answeredCount, fallbackIndex));
  }

  /* ── 1 + 3 — điểm yếu ──────────────────────────────────────────────────── */
  const weaknesses: NormalizedWeakness[] = [];

  for (const item of raw.weaknesses.slice(0, REPORT_ITEM_COUNT)) {
    const turnIndex = isValidTurnIndex(item.turnIndex, answeredCount)
      ? item.turnIndex
      : fallbackIndex;

    weaknesses.push({
      title: item.title,
      turnIndex,
      comment: item.comment,
      suggestion: item.suggestion,
      autoGenerated: false,
    });
  }

  while (weaknesses.length < REPORT_ITEM_COUNT) {
    weaknesses.push(autoWeakness(weaknesses.length, transcript, fallbackIndex));
  }

  /* ── 4 — đề xuất luyện tiếp ────────────────────────────────────────────── */
  const focusedList = focused ?? [];
  const validSkillIds = new Set(focusedList.map((item) => item.skillId));
  const validPractices = (raw.nextPractices ?? []).filter(
    (item) => validSkillIds.has(item.skillId) && item.action.trim().length > 0,
  );

  const nextPractices: NextPractice[] =
    validPractices.length > 0
      ? validPractices.slice(0, 3).map((item) => ({
          skillId: item.skillId,
          skillName: item.skillName,
          evidenceCount: item.evidenceCount,
          action: item.action,
        }))
      : buildFallbackPractices(focusedList);

  /* ── 5 — rubric + tổng điểm (tính lại) ───────────────────────────────── */
  const rubric = computeSessionRubric(
    transcript.map((turn) => ({
      kind: turn.kind,
      scores: Object.fromEntries(
        Object.entries(turn.rubric).map(([key, value]) => [
          key,
          { score: value, note: "" },
        ]),
      ),
    })),
  );

  const totals = answered
    .map((turn) => turn.total)
    .filter((value): value is number => typeof value === "number");
  const totalScore =
    totals.length > 0
      ? Math.round((totals.reduce((acc, value) => acc + value, 0) / totals.length) * 100) / 100
      : 0;

  return {
    overallNote: raw.overallNote,
    strengths,
    weaknesses,
    nextPractices,
    rubric,
    totalScore,
  };
}

/** Mục điểm mạnh tự sinh — KHÔNG bịa trích dẫn (R-MI-4). */
function autoStrength(
  slot: number,
  transcript: readonly TurnTranscript[],
  answeredCount: number,
  fallbackIndex: number,
): NormalizedStrength {
  const turn =
    transcript.find((t) => t.index === fallbackIndex) ?? transcript[answeredCount - 1];

  return {
    title: `Điểm mạnh ở lượt ${turn?.index ?? fallbackIndex}`,
    quote: null,
    turnIndex: turn?.index ?? fallbackIndex,
    comment:
      "Hệ thống tự tóm tắt từ điểm rubric của lượt này — chưa có nhận xét chi tiết từ AI.",
    autoGenerated: true,
  };
}

/** Mục điểm yếu tự sinh — KHÔNG bịa trích dẫn. */
function autoWeakness(
  slot: number,
  transcript: readonly TurnTranscript[],
  fallbackIndex: number,
): NormalizedWeakness {
  const turn = transcript.find((t) => t.index === fallbackIndex);

  return {
    title: `Lượt ${turn?.index ?? fallbackIndex} chưa đạt chuẩn`,
    turnIndex: turn?.index ?? fallbackIndex,
    comment: "Hệ thống tự tóm tắt từ điểm rubric thấp của lượt này.",
    suggestion: "Luyện lại dạng câu này và trả lời có số liệu + đánh đổi cụ thể.",
    autoGenerated: true,
  };
}
